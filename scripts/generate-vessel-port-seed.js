#!/usr/bin/env node
/**
 * Turns the game catalogs (src/assets/vessels.json, src/assets/aircraft-database-complete-
 * 2025-08.json and src/assets/ports.json) into INSERT statements for public.vessel and
 * public.port.
 *
 * Those two tables only hold an id (see "create table public.sql"), so the seed
 * carries no game data - just one row per catalog entry. The ids have to be the
 * uuids the frontend derives from the catalog integers, because
 * player_vessel.vessel_id and player_port.port_id are foreign keys into them:
 *
 *   catalogUuid(7) -> 00000000-0000-4000-8000-000000000007
 *
 * Aircraft are owned through the same player_vessel table, so their catalog ids also
 * need a row here. They are offset clear of the vessel ids (see AIRCRAFT_ID_BASE in
 * src/aircraftData.js) and assigned in file order; keep the two in step.
 *
 * Keep UUID() below in sync with catalogUuid() in src/api.js, otherwise claiming
 * a port fails on the foreign key.
 *
 * Run with: node scripts/generate-vessel-port-seed.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ASSETS = path.join(ROOT, 'src', 'assets');
const OUT = path.join(ROOT, 'insert vessel and port public.sql');

/** Mirrors catalogUuid() in src/api.js. */
function UUID(catalogId) {
  return `00000000-0000-4000-8000-${catalogId.toString(16).padStart(12, '0')}`;
}

function readCatalog(file, idKey) {
  const rows = JSON.parse(fs.readFileSync(path.join(ASSETS, file), 'utf8'));
  const seen = new Set();
  for (const row of rows) {
    const id = row[idKey];
    if (!Number.isInteger(id) || id < 0 || id > 0xffffffffffff) {
      throw new Error(`${file}: bad ${idKey} ${JSON.stringify(id)}`);
    }
    if (seen.has(id)) throw new Error(`${file}: duplicate ${idKey} ${id}`);
    seen.add(id);
  }
  // Sorted so re-running the generator produces a stable diff.
  return rows.slice().sort((a, b) => a[idKey] - b[idKey]);
}

function sqlEscape(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

/** One `('uuid'), -- id name` line per catalog entry, aligned into columns. */
function rows(rows, idKey, label) {
  const idWidth = String(rows[rows.length - 1][idKey]).length;
  const uuidWidth = UUID(rows[rows.length - 1][idKey]).length + 2;

  return rows.map((row) => {
    const id = String(row[idKey]).padStart(idWidth);
    const uuid = sqlEscape(UUID(row[idKey])).padEnd(uuidWidth);
    return `  ${uuid} -- ${id}  ${label(row)}`;
  });
}

/** Mirrors AIRCRAFT_ID_BASE in src/aircraftData.js. */
const AIRCRAFT_ID_BASE = 10000;

const vessels = readCatalog('vessels.json', 'id_vessel');
const ports = readCatalog('ports.json', 'id_port');

// Aircraft carry no id in the source dump, so one is assigned by position, exactly as
// src/aircraftData.js does when it builds the catalog at runtime.
const aircraft = JSON.parse(
  fs.readFileSync(path.join(ASSETS, 'aircraft-database-complete-2025-08.json'), 'utf8')
).map((plane, index) => ({
  id_vessel: AIRCRAFT_ID_BASE + index,
  label: `${plane.model} (${plane.typecode || 'Aircraft'})`,
}));

const vesselRows = rows(vessels, 'id_vessel', (v) => `${v.Company_Name} (${v.ship_name})`);
const aircraftRows = rows(aircraft, 'id_vessel', (a) => a.label);
const portRows = rows(ports, 'id_port', (p) => `${p.PORT_NAME} (${p.COUNTRY})`);

const sql = `-- Seed for public.vessel and public.port, generated by
-- scripts/generate-vessel-port-seed.js from src/assets/vessels.json, src/assets/aircraft-database-complete-2025-08.json
-- and src/assets/ports.json. Do not edit by hand - re-run the generator instead.
--
-- public.vessel and public.port only store an id (see "create table public.sql"),
-- so there is no game data to copy across: one row per catalog entry, keyed by
-- the uuids that src/api.js catalogUuid() derives from the catalog integers.
-- The trailing comment on each row is the catalog id and the display name, so
-- the file stays readable without a join.
--
-- Aircraft share public.vessel with ships (both are owned through player_vessel) but
-- have their own id range, starting at ${AIRCRAFT_ID_BASE}.
--
-- Safe to re-run: insert ... on conflict do nothing.

begin;

-- ${vessels.length} vessels
insert into public.vessel (id_vessel) values
${vesselRows.join(',\n')}
on conflict (id_vessel) do nothing;

-- ${aircraft.length} aircraft
insert into public.vessel (id_vessel) values
${aircraftRows.join(',\n')}
on conflict (id_vessel) do nothing;

-- ${ports.length} ports
insert into public.port (id_port) values
${portRows.join(',\n')}
on conflict (id_port) do nothing;

commit;
`;

fs.writeFileSync(OUT, sql);
console.log(
  `Wrote ${path.relative(ROOT, OUT)}: ${vessels.length} vessels, ${aircraft.length} aircraft, ${ports.length} ports.`
);
