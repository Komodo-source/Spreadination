// A stable object identity matters: react-leaflet re-applies `style` whenever the
// reference changes, which forces Leaflet to restyle and redraw the whole layer.
//
// Now that a real basemap draws the coastlines and the land, these outlines are an
// optional overlay rather than the map itself: no fill, because an opaque landmass
// would bury the bathymetry the game is played on, and a hairline stroke so they do
// not read as a second, slightly offset coastline.
