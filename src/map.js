/**
 * The vessel travelling along a route, drawn as a small triangle.
 *
 * A triangle reads as a heading where a circle does not: it points the way the ship is
 * going, and it is one SVG polygon, so it stays crisp at every zoom without an image. The
 * markup points north, which is what the CSS `rotate` the overlay applies expects.
 */
const VESSEL_ICON = L.divIcon({
  className: 'vessel-marker',
  html:
    '<svg aria-hidden="true" focusable="false" viewBox="0 0 24 24">' +
    '<polygon points="12 1.5 22.5 22 12 16.5 1.5 22" />' +
    '</svg>',
  iconSize: [22, 22],
  iconAnchor: [11, 11],
});

/**
 * The route line plus the vessel travelling along it.
 *
 * The vessel is a plain Leaflet layer rather than React state so it can be moved on
 * every animation frame without re-rendering the map's thousands of ports.
 */
const NavigationOverlay = memo(function NavigationOverlay({ distanceKm, fromPort, progress, route, toPort }) {
  const map = useMap();
  // SVG rather than canvas, for two reasons. The vessel moves every animation frame,
  // so it cannot share the ports' canvas without repainting the whole world; and a
  // second canvas would swallow clicks the same way the city canvas used to, because
  // it spans the entire viewport. An SVG overlay only catches events on its own paths.
  const renderer = useMemo(() => L.svg({ padding: VIEW_PADDING }), []);
  const vesselRef = useRef(null);
  const shownProgress = useRef(progress);
  const shownLabel = useRef(null);

  // The course a ship would actually sail. It comes from the voyage (seaRoute.js searched the
  // ocean grid for it), and it is cut where it crosses the antimeridian so Leaflet never
  // paints a line back across the whole map. A voyage with no route yet — an old one restored
  // from before routing existed — falls back to the great circle.
  const points = useMemo(
    () =>
      Array.isArray(route) && route.length > 1 ? route : greatCirclePoints(fromPort, toPort),
    [fromPort, route, toPort]
  );

  const legs = useMemo(() => splitAtAntimeridian(points), [points]);

  const destination = useMemo(() => toLatLng(toPort), [toPort]);

  const describe = useMemo(() => {
    const total = Number.isFinite(distanceKm) ? distanceKm : 0;

    return (value) => {
      const remaining = Math.max(0, Math.round(total * (1 - value / 100)));
      return `${Math.round(value)}% · ${remaining.toLocaleString()} km to run`;
    };
  }, [distanceKm]);

  /**
   * Moves the vessel to a point on the route and points it along the course.
   *
   * The heading is measured a fraction of a percent *ahead* of the vessel rather than at it,
   * so the triangle turns with the bend in the route instead of aiming at the tangent of the
   * point it is sitting on — and on a routed course it is what makes the ship swing round
   * Cape Horn instead of pointing at it. Near the destination there is nothing left to look
   * at, and the last heading is kept rather than snapping the triangle back north.
   */
  const paint = useCallback(
    (marker, value) => {
      if (!marker) return;

      marker.setLatLng(interpolateRoutePosition(points, value));

      const lookahead = Math.min(value, 100 - HEADING_LOOKAHEAD_PERCENT);
      const heading = mapHeadingDegrees(
        interpolateRoutePosition(points, lookahead),
        interpolateRoutePosition(points, lookahead + HEADING_LOOKAHEAD_PERCENT)
      );
      // The root element's transform belongs to Leaflet, which positions the layer with
      // it: the rotation goes on the SVG inside.
      const triangle = marker.getElement()?.firstElementChild;

      if (triangle && heading !== null) {
        triangle.style.transform = `rotate(${heading}deg)`;
      }
    },
    [points]
  );

  useEffect(() => {
    const marker = L.marker(
      interpolateRoutePosition(points, shownProgress.current),
      {
        icon: VESSEL_ICON,
        interactive: true,
        riseOnHover: true,
        zIndexOffset: 1000,
      }
    );

    shownLabel.current = describe(shownProgress.current);
    marker.bindTooltip(shownLabel.current, {
      className: 'vessel-tooltip',
      direction: 'top',
      offset: [0, -14],
    });
    marker.addTo(map);
    vesselRef.current = marker;
    paint(marker, shownProgress.current);

    return () => {
      marker.remove();
      vesselRef.current = null;
    };
  }, [describe, map, paint, points, shownProgress]);

  useEffect(() => {
    const marker = vesselRef.current;
    if (!marker) {
      return undefined;
    }

    const from = shownProgress.current;
    const to = progress;

    // Glide between the UI's progress steps instead of jumping once per tick, so the
    // ship slides along the arc rather than teleporting across it.
    if (from === to) {
      paint(marker, to);
      return undefined;
    }

    const startedAt = performance.now();
    let frame = 0;

    const step = (now) => {
      const ratio = Math.min(1, (now - startedAt) / NAVIGATION_TICK_MS);
      const value = from + (to - from) * ratio;

      shownProgress.current = value;
      paint(marker, value);

      const label = describe(value);
      if (label !== shownLabel.current) {
        shownLabel.current = label;
        marker.setTooltipContent(label);
      }

      if (ratio < 1) {
        frame = requestAnimationFrame(step);
      }
    };

    frame = requestAnimationFrame(step);

    return () => cancelAnimationFrame(frame);
  }, [describe, paint, progress]);

  return (
    <>
      {/* The course: dashes flow towards the destination (see .route-line in map.css). */}
      {legs.map((leg, index) => (
        <Polyline
          className="route-line"
          color="#00b4d8"
          dashArray="16 12"
          // A line spanning the map would otherwise take clicks meant for the ports it
          // passes over.
          interactive={false}
          key={`${fromPort.id_port}-${toPort.id_port}-${index}`}
          opacity={0.95}
          positions={leg}
          renderer={renderer}
          weight={4}
        />
      ))}
      {/* Destination port marker (when navigation is complete or nearly complete) */}
      {progress >= 95 && (
        <CircleMarker
          center={destination}
          className="arrival-marker"
          fillColor="#00ff00"
          fillOpacity={0.8}
          color="#00ff00"
          radius={12}
          renderer={renderer}
          weight={3}
        >
          <Tooltip>
            <div style={{ fontSize: '12px', fontWeight: 'bold' }}>
              Arrived at {toPort.PORT_NAME}
            </div>
          </Tooltip>
        </CircleMarker>
      )}
    </>
  );
});

/**
 * Everything that is expensive to rebuild. Memoised with stable props, so navigation
 * progress ticking twice a second no longer recreates thousands of React elements.
 */
const MapLayers = memo(function MapLayers({ onSelect, selectedId, claimedPortIds, showBorders }) {
  /**
   * One canvas for every static overlay, on purpose.
   *
   * A canvas has no per-shape DOM, so Leaflet emulates clicks by hit-testing the
   * shapes *registered on the canvas that received the event* — and each canvas is
   * sized to the whole (padded) viewport. One renderer per overlay therefore stacked
   * full-viewport canvases on top of the ports, and whichever landed on top swallowed
   * every click before the port canvas ever saw it. Sharing a single canvas makes the
   * hit test see all of them; the decorative layers opt out (see above) so the ports
   * always win.
   */
  const renderer = useMemo(() => L.canvas({ padding: VIEW_PADDING }), []);

  return (
    <>
      {showBorders && <CountryBorders renderer={renderer} />}
      <FallbackCities renderer={renderer} />
      <PortMarkers
        claimedPortIds={claimedPortIds}
        onSelect={onSelect}
        renderer={renderer}
        selectedId={selectedId}
      />
      <AirportMarkers
        onSelect={onSelect}
        renderer={renderer}
        selectedId={selectedId}
      />
    </>
  );
});


/**
 * Basemap picker plus the outline toggle.
 *
 * A plain absolutely-positioned panel rather than a Leaflet control, matching the
 * port panel and the attribution line, so the whole overlay stays React-owned.
 */
function MapLayersControl({ basemapId, onBasemapChange, mapRef, onSelectPort, onToggleBorders, showBorders }) {
  const [open, setOpen] = useState(false);
  const [openSearch, setOpenSearch] = useState(false);
  const [searchTerm, setSearchTerm] = useState("");

  const query = searchTerm.trim().toLowerCase();

  // Nothing is listed until the player types: showing all 3630 ports at once is
  // unreadable and makes the panel useless. Capped so a one-letter query stays snappy.
  const matches = useMemo(() => {
    if (!query) {
      return [];
    }

    return portData
      .filter((port) => port.PORT_NAME?.toLowerCase().includes(query))
      .slice(0, 50);
  }, [query]);

  // Picking a result centres the map on the port and opens its information panel, so the
  // search is a way to travel the map rather than a dead-end list of names.
  const selectPort = (port) => {
    const map = mapRef.current;

    if (map) {
      map.flyTo(port.position, Math.max(map.getZoom(), 6));
    }

    onSelectPort?.(port);
    setOpenSearch(false);
    setSearchTerm("");
  };

  return (
    <div className="map-control">


      <button
        aria-expanded={open}
        className="map-control-toggle"
        onClick={() => setOpen((current) => !current)}
        type="button"
      >
        Layers
      </button>
      {open && (
        <div aria-label="Map layers" className="map-control-panel" role="group">
          <p className="map-control-heading">Basemap</p>
          {BASEMAPS.map((basemap) => (
            <button
              className={`basemap-option${basemap.id === basemapId ? ' active' : ''}`}
              key={basemap.id}
              onClick={() => onBasemapChange(basemap.id)}
              type="button"
            >
              {basemap.label}
            </button>
          ))}
          <label className="layer-toggle">
            <input checked={showBorders} onChange={onToggleBorders} type="checkbox" />
            Country outlines
          </label>
        </div>
      )}
      <button
        aria-expanded={openSearch}
        className={`map-control-toggle${openSearch ? ' active' : ''}`}
        onClick={() => setOpenSearch((current) => !current)}
        type="button"
      >
        Search
      </button>
      {openSearch && (
        <div className="map-control-panel search-panel">
          <input
            aria-label="Search ports"
            autoFocus
            className="search-input"
            onChange={(event) => setSearchTerm(event.target.value)}
            placeholder="Search ports…"
            type="search"
            value={searchTerm}
          />

          <div className="search-results">
            {query && matches.length === 0 && (
              <p className="search-empty">No ports match “{searchTerm.trim()}”.</p>
            )}
            {matches.map((port) => (
              <button
                className="search-result"
                key={port.id}
                onClick={() => selectPort(port)}
                type="button"
              >
                <span
                  className={`search-flag fi fi-${(port.COUNTRY || 'xx').toLowerCase()}`}
                />
                <span className="search-result-text">
                  <span className="search-result-name">{port.PORT_NAME}</span>
                  <span className="search-result-country">{port.COUNTRY}</span>
                </span>
              </button>
            ))}
          </div>
        </div>
      )}
    </div>
  );
}

/**
 * Handy handle on the live Leaflet map for the overlays that sit outside `<MapContainer>`
 * (the search box), which cannot call `useMap()` themselves.
 */
function MapHandle({ mapRef }) {
  const map = useMap();

  useEffect(() => {
    mapRef.current = map;

    return () => {
      mapRef.current = null;
    };
  }, [map, mapRef]);

  return null;
}

function WorldMap({ voyages, claimedPorts, onClaimPort }) {
  const sailing = useMemo(() => voyages || [], [voyages]);
  // One selection for both layers. `kind`, set when portData and airportData are built,
  // decides which information panel opens; port ids are strings and airport ids are
  // numbers, so a single id can never match the wrong feature.
  const [selectedFeature, setSelectedFeature] = useState(null);
  const [basemapId, setBasemapId] = useState(DEFAULT_BASEMAP_ID);
  // Off by default: the basemap already draws the coastlines, and the Natural Earth
  // polygons disagree with it by a few hundred metres.
  const [showBorders, setShowBorders] = useState(false);
  const claimedPortIds = useMemo(() => new Set(claimedPorts || []), [claimedPorts]);
  const mapRef = useRef(null);

  const basemap = findBasemap(basemapId);

  return (
    <main className="map-shell" style={{ height: '100%', width: '100%', position: 'relative' }}>
      <div style={{ height: '100%', width: '100%' }}>
        <MapContainer
          attributionControl={false}
          center={[20, 0]}
          className="world-map"
          style={{ height: '100%', width: '100%', background: '#87ceeb' }} /* Water color */
          // The world repeats east to west. Drag past the antimeridian and Leaflet
          // jumps the view back to the equivalent spot on the original copy of the
          // world as it goes, which is what keeps the ports, routes and city markers —
          // all of them drawn in that one copy — in view the whole way round.
          //
          // There is deliberately no `maxBounds` here. It used to clamp the map to
          // ±180, and that is exactly what stopped the world repeating: the copy jump
          // moved the view onto the wrapped world and the bounds snapped it straight
          // back, so a pan past the edge stuck and jittered instead of carrying on.
          worldCopyJump
          // Zoom 2 is the smallest useful world view: at zoom 1 the whole world is
          // narrower than the viewport and repeats on screen more than once.
          minZoom={2}
          maxZoom={MAX_MAP_ZOOM}
          preferCanvas
          scrollWheelZoom
          // A short debounce paired with a small wheel step keeps a scroll gesture from
          // firing several zoom animations that interrupt each other.
          wheelDebounceTime={40}
          wheelPxPerZoomLevel={60}
          zoom={3}
        >
          {/*
            `key` is deliberate: Leaflet cannot change a tile layer's native zoom in
            place, so switching basemap has to build a fresh layer. The layer is left
            wrapping its coordinates, so it fetches the repeated copies of the world
            as the view crosses the antimeridian — without them the map would run out
            of tiles at the edge, which is what used to stop the pan.
          */}
          <TileLayer
            attribution={basemap.attribution}
            key={basemap.id}
            maxNativeZoom={basemap.maxNativeZoom}
            maxZoom={MAX_MAP_ZOOM}
            url={basemap.url}
          />
          <MapLayers
            onSelect={setSelectedFeature}
            selectedId={selectedFeature ? selectedFeature.id : null}
            claimedPortIds={claimedPortIds}
            showBorders={showBorders}
          />
          {/*
            One overlay per occupied vessel, so a whole fleet can be under way at once.

            The props are the voyage's stable parts plus its progress: passing the whole
            voyage object would change identity on every tick and rebuild the route line
            and the vessel marker twice a second.
          */}
          {sailing.map((voyage) => (
            <NavigationOverlay
              distanceKm={voyage.distanceKm}
              fromPort={voyage.fromPort}
              key={voyage.id}
              progress={voyage.progress}
              route={voyage.route}
              toPort={voyage.toPort}
            />
          ))}
          <ScaleControl position="bottomleft" />
          <MapHandle mapRef={mapRef} />
        </MapContainer>
      </div>
      <MapLayersControl
        basemapId={basemapId}
        mapRef={mapRef}
        onBasemapChange={setBasemapId}
        onSelectPort={setSelectedFeature}
        onToggleBorders={() => setShowBorders((current) => !current)}
        showBorders={showBorders}
      />
      {/*
        The subject of the selection decides the panel. Passing an airport to PortPanel is
        what used to throw on `port.COUNTRY.toUpperCase()` the moment an airport was
        clicked; airports now get a panel that only reads fields they actually have.
      */}
      {selectedFeature?.kind === 'airport' ? (
        <AirportPanel airport={selectedFeature} onClose={() => setSelectedFeature(null)} />
      ) : (
        <PortPanel
          claimed={selectedFeature ? claimedPortIds.has(selectedFeature.id_port) : false}
          onAcquire={onClaimPort}
          onClose={() => setSelectedFeature(null)}
          port={selectedFeature}
        />
      )}
      <div className="map-attribution">
        {basemap.attribution}
        {showBorders && (
          <>
            {' · Outlines: '}
            <a href="https://github.com/nvkelso/natural-earth-vector">Natural Earth</a>
          </>
        )}
      </div>
    </main>
  );
}

export default WorldMap;
